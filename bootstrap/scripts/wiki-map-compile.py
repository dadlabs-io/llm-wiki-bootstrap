#!/usr/bin/env python3
"""
Compile a compressed always-loaded _MAP.md for a topic wiki.

This is Asel L2 tier-1 material: a ~3K-token compressed orientation document
loaded into every agent conversation. Per-folder _INDEX.md files are tier-2
(loaded when working in an area); full entries are tier-3 (on demand).

_MAP.md layout:
  - What the wiki is (2-3 sentences)
  - Starting points: HOME.md + hub pages
  - Folder directory: one line per folder — purpose + count + top entries
    (top N by tier, tie-broken by recency)
  - Pointer to concept-gaps (only when the wiki has that page)
  - Pointer to the full _INDEX.md (only when one exists: the topic root,
    else wiki/_INDEX.md)

The file is fully auto-generated from frontmatter + folder READMEs + the
current state of the wiki. Regenerate on every cycle.

Usage
-----
    python wiki-map-compile.py --topic <topic> \\
        --vault llm-wiki/wiki

    # Dry-run:
    python wiki-map-compile.py --topic <topic> --dry-run

    # Cycle-contract JSON emission:
    python wiki-map-compile.py --topic <topic> \\
        --cycle-id 2026-04-24-01 \\
        --run-folder docker/.../_inbox/reports/2026-04-24/2026-04-24-01/

Cycle contract
--------------
When --cycle-id and --run-folder are supplied, writes
<run-folder>/map-compile.json (+ .md) per the schema in
wiki/best-practices/cycle-step-return-format.md. Step name: "map-compile".
"""

